// Helper to pick a random item from an array different from the current value if possible
function pickRandom(arr, currentVal) {
  if (!arr || !arr.length) return "";
  if (arr.length === 1) return arr[0];
  const filtered = arr.filter(item => item !== currentVal);
  const pool = filtered.length > 0 ? filtered : arr;
  const idx = Math.floor(Math.random() * pool.length);
  return pool[idx];
}

